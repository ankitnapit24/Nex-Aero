import React, { useEffect, useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { RefreshCw } from 'lucide-react';
import {
  CartesianGrid, Line, LineChart, ResponsiveContainer, Tooltip, XAxis, YAxis,
} from 'recharts';
import api, { getApiErrorMessage } from '../services/api';
import { formatEngine, formatRul, formatTimestamp, PageHeading, Panel, PanelHeading, RiskBadge, StateBlock } from '../components/UI/Shared';
import { usePreferences } from '../i18n/Preferences';

export default function PredictionHistory() {
  const { t } = usePreferences();
  const [records, setRecords] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [engineFilter, setEngineFilter] = useState('ALL');
  const [dateFilter, setDateFilter] = useState('');

  const loadHistory = async () => {
    setLoading(true);
    setError('');
    try {
      setRecords(await api.getPredictions(1000));
    } catch (requestError) {
      setError(getApiErrorMessage(requestError));
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => { loadHistory(); }, []);

  const engineIds = useMemo(() => [...new Set(records.map((record) => record.engine_id))].sort((a, b) => a - b), [records]);
  const filtered = records.filter((record) => (
    (engineFilter === 'ALL' || String(record.engine_id) === engineFilter)
    && (!dateFilter || String(record.created_at).slice(0, 10) >= dateFilter)
  ));
  const trend = filtered
    .filter((record) => engineFilter !== 'ALL' && String(record.engine_id) === engineFilter)
    .slice()
    .reverse()
    .map((record) => ({ recorded: formatTimestamp(record.created_at), predicted: Number(record.predicted_rul), cycle: record.cycle }));

  return (
    <div className="page-stack">
      <PageHeading
        eyebrow="BACKEND AUDIT LOG"
        title="Prediction history"
        description="Track stored RUL estimates and review how predictions change over time."
        actions={<button className="button button-outline" onClick={loadHistory} disabled={loading}><RefreshCw size={15} className={loading ? 'spin' : ''} /> {t('Refresh records')}</button>}
      />
      <Panel>
        <PanelHeading title="Stored inference records" description="Records are fetched from the backend audit endpoint; no history is generated by the frontend." />
        <div className="filter-row">
          <label className="filter-field"><span>{t('Engine')}</span><select className="form-select" value={engineFilter} onChange={(event) => setEngineFilter(event.target.value)}><option value="ALL">{t('All engines')}</option>{engineIds.map((id) => <option key={id} value={id}>{formatEngine(id)}</option>)}</select></label>
          <label className="filter-field"><span>{t('From date')}</span><input className="form-select" type="date" value={dateFilter} onChange={(event) => setDateFilter(event.target.value)} /></label>
          <span className="filter-count">{loading ? t('Loading…') : `${filtered.length} ${t(filtered.length === 1 ? 'record' : 'records')} ${t('shown')}`}</span>
        </div>
        {loading || error || filtered.length === 0 ? <StateBlock loading={loading} error={error} empty={!loading && !error ? 'No matching prediction records. Inference records appear here after a prediction is stored.' : ''} onRetry={loadHistory} /> : (
          <div className="table-scroll"><table className="data-table"><thead><tr><th>{t('Recorded at')}</th><th>{t('Engine')}</th><th>{t('Cycle')}</th><th>{t('Estimated RUL')}</th><th>{t('Tier')}</th><th>{t('Model version')}</th><th /></tr></thead><tbody>
            {filtered.map((record) => <tr key={record.id}><td>{formatTimestamp(record.created_at)}</td><td>{formatEngine(record.engine_id)}</td><td className="numeric">{record.cycle}</td><td className="numeric rul-value">{formatRul(record.predicted_rul)}</td><td><RiskBadge tier={record.urgency_tier} /></td><td>{record.model_version || '—'}</td><td><Link className="text-link" to={`/engines/${record.engine_id}`}>{t('View engine')}</Link></td></tr>)}
          </tbody></table></div>
        )}
      </Panel>
      {engineFilter !== 'ALL' && (
        <Panel>
          <PanelHeading title={`${formatEngine(engineFilter)} ${t('estimate trend')}`} description="Stored estimates for this engine, in record order." />
          {trend.length < 2 ? <StateBlock empty="At least two stored estimates for this engine are needed to show a trend." /> : (
            <div className="chart-wrap chart-sensor">
              <ResponsiveContainer width="100%" height="100%">
                <LineChart data={trend} margin={{ top: 12, right: 12, bottom: 2, left: -10 }}>
                  <CartesianGrid stroke="#e8e4dc" strokeDasharray="3 5" />
                  <XAxis dataKey="cycle" tickLine={false} axisLine={false} tick={{ fill: '#77746d', fontSize: 11 }} label={{ value: t('Operating cycle'), position: 'insideBottom', offset: -2, fill: '#77746d', fontSize: 11 }} />
                  <YAxis dataKey="predicted" domain={['auto', 'auto']} tickLine={false} axisLine={false} tick={{ fill: '#77746d', fontSize: 10 }} width={55} />
                  <Tooltip contentStyle={{ background: '#fbfaf7', border: '1px solid #d4d1ca', borderRadius: 8, fontSize: 12 }} labelFormatter={(cycle) => `${t('Cycle')} ${cycle}`} formatter={(value) => [`${Number(value).toFixed(1)} ${t('cycles')}`, t('Estimated RUL')]} />
                  <Line type="monotone" dataKey="predicted" stroke="#c66f5e" strokeWidth={2} dot={{ r: 3, fill: '#c66f5e' }} isAnimationActive={false} />
                </LineChart>
              </ResponsiveContainer>
            </div>
          )}
        </Panel>
      )}
    </div>
  );
}
